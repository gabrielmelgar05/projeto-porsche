export type Locale = "en" | "pt";

export type SectionId = "precision" | "aerodynamics" | "showroom" | "details" | "performance" | "interior";

export type Tone = "light" | "dark";

export type ViewId = "front34" | "side" | "rear34" | "front" | "rear";
export type PaintId = "white" | "black";

export type HotspotId =
  "rearWing" | "frontAero" | "wheelsBrakes" | "carbon" | "diffuser" | "cockpit" | "seats";

export type SceneId = "front34" | "rear34" | "cockpit";

/** One photograph in the image manifest. */
export interface ImageAsset {
  /** Stable id, also the key for alt text in the dictionaries. */
  id: string;
  /** Public directory, e.g. "showroom". */
  dir: string;
  /** File stem; variants are `<stem>-<width>.avif|webp`. */
  name: string;
  /** Intrinsic master size — fixes the aspect ratio (no layout shift). */
  width: number;
  height: number;
  /** Responsive widths generated by `npm run images`. */
  widths: readonly number[];
  /** Optional art-directed crop for small screens (portrait). */
  mobile?: { name: string; width: number; height: number };
  /** CSS object-position, for fine framing once the file exists. */
  focus?: string;
}
